"""memo()
abs()関数は絶対値を返す関数

フォーマット指定について
-:埋め文字。余った桁を”-"で埋める
>:右揃え
8:全体の幅を８文字にする
.3:小数点以下を３桁まで表示する
f:floatとして表示
"""  
print("{0:05b}".format(b)) #変数bの値を５桁の２進数で、余った桁を０埋め
#{0:...}フォーマット対象。最初の０はformat()に渡した最初の引数(b)を指す
#05全体の幅を５桁にし、足りない部分を０で埋める
#２進数(binary)として表示する指定
